'use strict';

// Run with: node --test scripts/schema-drift.test.js   (Node built-ins only)
// scripts/schema-drift.sh against a fake Supabase CLI and Docker on PATH [SCHEMA-DRIFT] (SEC-08).

const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { test } = require('node:test');

const SCRIPT = path.join(__dirname, 'schema-drift.sh');

/** A throwaway repo with the script, a migrations folder and fake `supabase`/`docker` binaries. */
function sandbox({ version = '3.1.0', diff = '', diffExit = 0, linked = true } = {}) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'schema-drift-'));
    fs.mkdirSync(path.join(root, 'scripts'));
    fs.copyFileSync(SCRIPT, path.join(root, 'scripts', 'schema-drift.sh'));
    fs.mkdirSync(path.join(root, 'supabase', 'migrations'), { recursive: true });
    if (linked) {
        fs.mkdirSync(path.join(root, 'supabase', '.temp'));
        fs.writeFileSync(path.join(root, 'supabase', '.temp', 'project-ref'), 'ref');
    }
    const bin = path.join(root, 'bin');
    fs.mkdirSync(bin);
    const calls = path.join(root, 'calls.log');
    fs.writeFileSync(path.join(root, 'diff.sql'), diff);
    const fake = `#!/usr/bin/env bash
echo "$*" >> "${calls}"
case "$1" in
  --version) echo "${version}" ;;
  db) cat "${path.join(root, 'diff.sql')}"; exit ${diffExit} ;;
esac
exit 0
`;
    fs.writeFileSync(path.join(bin, 'supabase'), fake, { mode: 0o755 });
    fs.writeFileSync(path.join(bin, 'docker'), '#!/usr/bin/env bash\nexit 0\n', { mode: 0o755 });
    const run = (env = {}) => {
        const r = spawnSync('bash', [path.join(root, 'scripts', 'schema-drift.sh')], {
            env: { PATH: `${bin}:/usr/bin:/bin`, ...env },
            encoding: 'utf8',
        });
        const log = fs.existsSync(calls) ? fs.readFileSync(calls, 'utf8') : '';
        fs.rmSync(root, { recursive: true, force: true });
        return { code: r.status, out: r.stdout + r.stderr, calls: log };
    };
    return { run };
}

test('no drift: a diff of blank and comment lines only exits 0', () => {
    const r = sandbox({ diff: '\n-- generated by the CLI\n   \n' }).run();
    assert.equal(r.code, 0, r.out);
    assert.match(r.out, /OK, the remote schema matches/);
});

test('drift: any SQL in the diff exits 1 and prints it', () => {
    const r = sandbox({ diff: 'alter table public.games add column x int;\n' }).run();
    assert.equal(r.code, 1, r.out);
    assert.match(r.out, /DRIFT FOUND/);
    assert.match(r.out, /alter table public\.games add column x int;/);
});

test('a failing diff is "unknown", exit 2, never clean', () => {
    const r = sandbox({ diffExit: 1 }).run();
    assert.equal(r.code, 2, r.out);
    assert.match(r.out, /drift is UNKNOWN/);
});

test('CLI v3 uses --remote; CLI 2.x uses --linked; only the public schema by default', () => {
    assert.match(sandbox({ version: '3.1.0' }).run().calls, /db diff --remote --schema public/);
    assert.match(sandbox({ version: '2.40.1' }).run().calls, /db diff --linked --schema public/);
});

test('not linked and no project ref: exit 2', () => {
    const r = sandbox({ linked: false }).run();
    assert.equal(r.code, 2, r.out);
    assert.match(r.out, /not linked/);
});

test('a project ref without its access token or password: exit 2, nothing linked', () => {
    const noToken = sandbox({ linked: false }).run({ SUPABASE_PROJECT_REF: 'abc' });
    assert.equal(noToken.code, 2);
    assert.doesNotMatch(noToken.calls, /link/);
    const noPassword = sandbox({ linked: false }).run({ SUPABASE_PROJECT_REF: 'abc', SUPABASE_ACCESS_TOKEN: 't' });
    assert.equal(noPassword.code, 2);
});

test('with a project ref and credentials it links first, then diffs', () => {
    const r = sandbox({ linked: false }).run({
        SUPABASE_PROJECT_REF: 'abc',
        SUPABASE_ACCESS_TOKEN: 't',
        SUPABASE_DB_PASSWORD: 'p',
    });
    assert.equal(r.code, 0, r.out);
    assert.match(r.calls, /^link --project-ref abc$/m);
    assert.ok(r.calls.indexOf('link') < r.calls.indexOf('db diff'));
});
